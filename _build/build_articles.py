def related(i):
    a = ARTICLES[i]
    same = [o for o in ARTICLES if o is not a and o["tag"] == a["tag"]]
    rest = [ARTICLES[(i + k) % len(ARTICLES)] for k in range(1, len(ARTICLES))]
    out = []
    for o in same + rest:
        if o not in out:
            out.append(o)
    return out[:3]


